import AppKit
import SimKit
import SwiftUI

/// AppKit hit surface in the Duo's visible display coordinates. CoreSimulator
/// rotates the inner framebuffer pixels, but its digitizer expects points in
/// the already-upright display coordinate system.
final class DuoPointerView: NSView {
    weak var runtime: IOSSimulatorRuntime?
    weak var screen: SimulatorScreenView?
    var targetScreenID: UInt32 = 1
    private var dragEdge: DeviceEdge?
    private var lastTouchPoint = CGPoint.zero
    private var touching = false
    private var twoFinger = false
    /// Synthetic finger driven by trackpad scroll phases. Streaming the scroll as one
    /// continuous touch avoids SimKit's blocking 120 ms swipe per scroll event, which was
    /// the main source of input lag on the Duo.
    private var scrollPoint: CGPoint?

    override var isFlipped: Bool { true }
    override var acceptsFirstResponder: Bool { true }

    private var projectedDisplay: DuoActiveDisplay? {
        guard runtime?.is3DPoseActive == true else { return nil }
        return targetScreenID == IOSSimulatorRuntime.duoInnerScreenID ? .inner : .outer
    }

    override func hitTest(_ point: NSPoint) -> NSView? {
        if let display = projectedDisplay {
            let windowPoint = superview?.convert(point, to: nil) ?? point
            guard runtime?.flipRenderer?.digitizerPoint(at: windowPoint, for: display) != nil else { return nil }
        }
        return super.hitTest(point)
    }

    private var activeScreen: SimulatorScreenView? {
        if let current = runtime?.screenView {
            screen = current
            return current
        }
        return screen
    }

    override func mouseDown(with event: NSEvent) {
        guard let visual = normalizedPoint(event) else { return }
        // Re-assert the HID panel on every touch: the screen view can be rebuilt
        // (fold, rotation, relaunch) and lose the target, silently dropping touches.
        let targetScreen = activeScreen
        targetScreen?.targetPanel(screenId: targetScreenID)
        lastTouchPoint = visual
        endScrollTouch()
        twoFinger = event.modifierFlags.contains(.option)
        if twoFinger {
            dragEdge = nil
            touching = targetScreen?.sendTwoFingerTouch(.down, first: visual, second: mirror(visual)) == true
        } else {
            let upright = projectedDisplay == nil ? uprightPoint(event) : fromDigitizer(visual)
            dragEdge = edge(for: upright).map(digitizerEdge)
            touching = targetScreen?.sendTouch(.down, normalized: visual, edge: dragEdge) == true
        }
        if !touching { DebugLog.write("Duo touch unavailable: screenAttached=\(targetScreen != nil)") }
        runtime?.focusMacKeyboard(in: self, at: event.locationInWindow)
    }

    override func keyDown(with event: NSEvent) {
        if window?.firstResponder === self,
           let keyboard = runtime?.focusMacKeyboard(in: self, at: convert(CGPoint(x: bounds.midX, y: bounds.midY), to: nil)) {
            keyboard.keyDown(with: event)
        } else {
            super.keyDown(with: event)
        }
    }

    override func mouseDragged(with event: NSEvent) {
        guard touching else { return }
        guard let p = normalizedPoint(event) else { return }
        lastTouchPoint = p
        if twoFinger {
            _ = activeScreen?.sendTwoFingerTouch(.move, first: p, second: mirror(p))
        } else {
            _ = activeScreen?.sendTouch(.move, normalized: p, edge: dragEdge)
        }
    }

    override func mouseUp(with event: NSEvent) {
        guard touching else { return }
        let p = normalizedPoint(event) ?? lastTouchPoint
        if twoFinger {
            _ = activeScreen?.sendTwoFingerTouch(.up, first: p, second: mirror(p))
        } else {
            _ = activeScreen?.sendTouch(.up, normalized: p, edge: dragEdge)
        }
        touching = false
        twoFinger = false
        dragEdge = nil
    }

    override func scrollWheel(with event: NSEvent) {
        guard !touching, let screen = activeScreen else { return }
        // Momentum is generated by iOS from the release velocity.
        guard event.momentumPhase.isEmpty else { return }
        let ux = event.scrollingDeltaX / max(bounds.width, 1)
        let uy = event.scrollingDeltaY / max(bounds.height, 1)
        // Deltas are in the upright picture; rotate them like points.
        let delta: CGSize
        if let display = projectedDisplay, let renderer = runtime?.flipRenderer,
           let start = normalizedPoint(event) {
            let point = event.locationInWindow
            let end = CGPoint(x: point.x + event.scrollingDeltaX, y: point.y - event.scrollingDeltaY)
            let next = renderer.digitizerPoint(at: end, for: display) ?? start
            delta = CGSize(width: next.x - start.x, height: next.y - start.y)
        } else {
            delta = digitizerDelta(dx: ux, dy: uy)
        }
        let dx = delta.width
        let dy = delta.height
        screen.targetPanel(screenId: targetScreenID)
        if event.hasPreciseScrollingDeltas {
            if event.phase.contains(.began) || scrollPoint == nil {
                guard !event.phase.contains(.ended), !event.phase.contains(.cancelled) else { return }
                guard let start = normalizedPoint(event) else { return }
                scrollPoint = start
                _ = screen.sendTouch(.down, normalized: start)
            }
            if var p = scrollPoint, event.phase.contains(.changed) || event.phase.isEmpty {
                p.x = clamp(p.x + dx); p.y = clamp(p.y + dy)
                scrollPoint = p
                _ = screen.sendTouch(.move, normalized: p)
            }
            if event.phase.contains(.ended) || event.phase.contains(.cancelled) { endScrollTouch() }
        } else {
            // Mouse wheel: short streamed flick, scheduled rather than slept on main.
            guard let start = normalizedPoint(event) else { return }
            let end = CGPoint(x: clamp(start.x + dx * 8), y: clamp(start.y + dy * 8))
            _ = screen.sendTouch(.down, normalized: start)
            for step in 1...6 {
                let f = CGFloat(step) / 6
                let p = CGPoint(x: start.x + (end.x - start.x) * f, y: start.y + (end.y - start.y) * f)
                DispatchQueue.main.asyncAfter(deadline: .now() + .milliseconds(10 * step)) { [weak screen] in
                    _ = screen?.sendTouch(step == 6 ? .up : .move, normalized: p)
                }
            }
        }
    }

    private func endScrollTouch() {
        guard let p = scrollPoint else { return }
        _ = activeScreen?.sendTouch(.up, normalized: p)
        scrollPoint = nil
    }

    private func mirror(_ p: CGPoint) -> CGPoint { CGPoint(x: 1 - p.x, y: 1 - p.y) }

    /// The digitizer uses the unrotated IOSurface's pixel coordinates. Keep
    /// gestures aligned with the displayed image for every device orientation.
    var quarterTurns = 0

    private func uprightPoint(_ event: NSEvent) -> CGPoint {
        let point = convert(event.locationInWindow, from: nil)
        return CGPoint(x: clamp(point.x / max(bounds.width, 1)), y: clamp(point.y / max(bounds.height, 1)))
    }

    private func toDigitizer(_ p: CGPoint) -> CGPoint {
        switch quarterTurns {
        case 1: CGPoint(x: p.y, y: 1 - p.x)
        case 2: CGPoint(x: 1 - p.x, y: 1 - p.y)
        case 3: CGPoint(x: 1 - p.y, y: p.x)
        default: p
        }
    }

    private func fromDigitizer(_ d: CGPoint) -> CGPoint {
        switch quarterTurns {
        case 1: CGPoint(x: 1 - d.y, y: d.x)
        case 2: CGPoint(x: 1 - d.x, y: 1 - d.y)
        case 3: CGPoint(x: d.y, y: 1 - d.x)
        default: d
        }
    }

    private func digitizerDelta(dx: CGFloat, dy: CGFloat) -> CGSize {
        switch quarterTurns {
        case 1: CGSize(width: dy, height: -dx)
        case 2: CGSize(width: -dx, height: -dy)
        case 3: CGSize(width: -dy, height: dx)
        default: CGSize(width: dx, height: dy)
        }
    }

    private func digitizerEdge(_ edge: DeviceEdge) -> DeviceEdge {
        switch (quarterTurns, edge) {
        case (1, .top), (2, .right), (3, .bottom): .left
        case (1, .bottom), (2, .left), (3, .top): .right
        case (1, .left), (2, .bottom), (3, .right): .bottom
        case (1, .right), (2, .top), (3, .left): .top
        default: edge
        }
    }

    private func normalizedPoint(_ event: NSEvent) -> CGPoint? {
        if let display = projectedDisplay {
            return runtime?.flipRenderer?.digitizerPoint(at: event.locationInWindow, for: display)
        }
        return toDigitizer(uprightPoint(event))
    }

    /// System edge gestures need the edge flag on touch-down, but flagging too wide a
    /// strip steals ordinary taps. In particular the multitasking "•••" control sits at
    /// the top centre; tagging it `.top` turns a tap into a Notification Centre pull and
    /// makes Split View unreachable. Keep the top centre clear and expose left/right edges
    /// so Slide Over / side drags work.
    private func edge(for point: CGPoint) -> DeviceEdge? {
        if point.y >= 0.985 { return .bottom }
        if point.y <= 0.006 && !(0.38...0.62).contains(point.x) { return .top }
        if point.x <= 0.006 { return .left }
        if point.x >= 0.994 { return .right }
        return nil
    }

    private func clamp(_ value: CGFloat) -> CGFloat { min(1, max(0, value)) }
}

struct DuoPointerSurface: NSViewRepresentable {
    let runtime: IOSSimulatorRuntime
    let screenID: UInt32
    var quarterTurns = 0

    func makeNSView(context: Context) -> NSView {
        let view = DuoPointerView(frame: .zero)
        view.runtime = runtime
        view.targetScreenID = screenID
        view.quarterTurns = quarterTurns
        runtime.pointerView = view
        return view
    }

    func updateNSView(_ nsView: NSView, context: Context) {
        guard let view = nsView as? DuoPointerView else { return }
        view.runtime = runtime
        view.targetScreenID = screenID
        view.quarterTurns = quarterTurns
        runtime.pointerView = view
    }

    static func dismantleNSView(_ nsView: NSView, coordinator: ()) {
        guard let view = nsView as? DuoPointerView else { return }
        if view.runtime?.pointerView === view { view.runtime?.pointerView = nil }
        view.screen = nil
    }
}
